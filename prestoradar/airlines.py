"""Callsign -> operator name, for the tap-to-inspect panel.

The lookup half of airlines_data.py (generated by make_airlines.py from the
OpenFlights database). An ADS-B airline callsign is a 3-letter ICAO operator
prefix followed by a flight number -- SKW4397 -> SkyWest. Registrations
(N-numbers, G-BABC, ...) and the bare hex-id fallback have no operator prefix
and return None.
"""

from airlines_data import OPERATORS


def operator(callsign):
    """"SkyWest" for "SKW4397", or None when the callsign carries no airline
    prefix -- a registration, a bare ICAO hex id, or an unknown code."""
    if not callsign:
        return None
    cs = callsign.strip().upper()
    # An airline callsign is exactly three letters, then a digit (the start of
    # the flight number). "N172SP", "GABCD", "A1B2C3" all fail this.
    if len(cs) < 4 or not cs[:3].isalpha() or not cs[3].isdigit():
        return None
    return OPERATORS.get(cs[:3])
