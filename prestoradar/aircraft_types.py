"""ICAO type designator -> human-readable model, for the tap-to-inspect panel.

The lookup half of aircraft_types_data.py (generated by make_aircraft_types.py
from ICAO Doc 8643). The feed's own `desc` field wins at read time -- see
plane.Plane.type_description; this is only the fallback for when adsb.lol
omits it (military, some GA, blocked airframes).
"""

from aircraft_types_data import TYPES


def describe(type_code):
    """"Boeing 737-800" for "B738", or None if the code is blank or unknown."""
    if not type_code:
        return None
    return TYPES.get(type_code.strip().upper())
