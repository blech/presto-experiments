# Flat local frame: 1 degree of latitude is 60 nm; a degree of longitude shrinks
# by cos(latitude).
KM_PER_DEG_LAT = 60.0 * 1.852
KM_PER_DEG_LON = KM_PER_DEG_LAT * math.cos(math.radians(CENTER_LAT))
KNOT_TO_KM_S = 1.852 / 3600.0        # knots -> km travelled per second
PX_PER_KM = 230.0 / RADIUS_KM        # outer ring sits at RADIUS_KM

_log_sock = None

def log_init():
    # Called once the network is up. Best-effort UDP broadcast socket.
    global _log_sock
    if not LOG_UDP_PORT:
        return
    try:
        import socket
        s = socket.socket(socket.AF_INET, socket.SOCK_DGRAM)
        s.setsockopt(socket.SOL_SOCKET, socket.SO_BROADCAST, 1)
        _log_sock = s
    except Exception as e:  # noqa: BLE001
        print("log_init: no UDP:", repr(e))

def log(*parts):
    line = "[{:8.2f}] {}".format(time.ticks_ms() / 1000, " ".join(str(p) for p in parts))
    print(line)
    if _log_sock is not None:
        try:
            _log_sock.sendto(line.encode(), LOG_UDP_ADDR)
        except Exception:
            pass


def project(lat, lon):
    # Geographic position -> kilometres east / north of the centre.
    east = (lon - CENTER_LON) * KM_PER_DEG_LON
    north = (lat - CENTER_LAT) * KM_PER_DEG_LAT
    return east, north

def to_screen(east_km, north_km):
    # Metric frame -> 480x480 pixels, centre at (240, 240), north is up.
    return int(240 + east_km * PX_PER_KM), int(240 - north_km * PX_PER_KM)

