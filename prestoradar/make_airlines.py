"""
Generate prestoradar/airlines_data.py -- an ICAO-airline-code -> operator-name
table for the tap-to-inspect panel, from the OpenFlights airline database
(https://openflights.org/data, ODbL).

Desktop tool, standard library only. It fetches OpenFlights' airlines.dat,
keeps every row with a real 3-letter ICAO code (the prefix an ADS-B callsign
starts with -- SKW4397 -> SKW), and writes { code: name } out as a Python
module, the same build-time pattern as make_basemap.py -> basemap_data.py.

Typical use:

    python3 prestoradar/make_airlines.py              # active carriers only (~1k)
    python3 prestoradar/make_airlines.py --all        # every ICAO code (~5.8k)
    python3 prestoradar/make_airlines.py --keep seen.txt   # + codes from a capture
    python3 prestoradar/make_airlines.py --source path/to/airlines.dat

By default only rows OpenFlights marks active are kept, to stay small enough
for the Presto bundle (DATA-TODOS.md #2: "keep the first cut tiny"). That flag
is unreliable, so _OVERRIDES and an optional --keep list (one ICAO code per
line, e.g. harvested with dev/list_aircraft.py) are always included on top.
--all emits the full table for the desktop / Tidbyt lookup service, where size
doesn't matter. When a code is reused across rows, an active row wins, then an
earlier one. _OVERRIDES also shortens names for the 64-pixel panel -- edit
that, not airlines_data.py.
"""

import argparse
import csv
import os
import re
import sys
import urllib.request

SOURCE_URL = "https://raw.githubusercontent.com/jpatokal/openflights/master/data/airlines.dat"
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "airlines_data.py")

_ICAO_RE = re.compile(r"^[A-Z]{3}$")

# code -> name: applied last, wins over OpenFlights. Use for carriers OpenFlights
# has wrong/stale, and to shorten names for the panel (keep these <= ~16 chars).
_OVERRIDES = {
    "AAL": "American",
    "ACA": "Air Canada",
    "AAY": "Allegiant",
    "ASA": "Alaska",
    "AFR": "Air France",
    "BAW": "British Airways",
    "DAL": "Delta",
    "DLH": "Lufthansa",
    "EJA": "NetJets",
    "FDX": "FedEx",
    "FFT": "Frontier",
    "JBU": "JetBlue",
    "JZA": "Air Canada Jazz",
    "KLM": "KLM",
    "NKS": "Spirit",
    "QXE": "Horizon Air",
    "RPA": "Republic",
    "SKW": "SkyWest",
    "SWA": "Southwest",
    "SWR": "Swiss",
    "UAL": "United",
    "UPS": "UPS",
    "VOI": "Volaris",
    "WJA": "WestJet",
}


def _load_rows(source):
    if source:
        with open(source, newline="", encoding="utf-8") as fh:
            return list(csv.reader(fh))
    with urllib.request.urlopen(SOURCE_URL, timeout=30) as resp:
        text = resp.read().decode("utf-8")
    return list(csv.reader(text.splitlines()))


def build(source=None, keep_all=False, keep=()):
    """OpenFlights airlines.dat -> { icao_code: operator_name }."""
    # id, name, alias, iata, icao, callsign, country, active
    keep = {c.strip().upper() for c in keep if c.strip()}
    best = {}   # code -> (active_bool, -row_index, name)
    for i, row in enumerate(_load_rows(source)):
        if len(row) < 8:
            continue
        name, icao, active = row[1].strip(), row[4].strip(), row[7].strip()
        if not _ICAO_RE.match(icao) or not name or name in ("Unknown", "Private flight"):
            continue
        if not (keep_all or active == "Y" or icao in _OVERRIDES or icao in keep):
            continue
        cand = (active == "Y", -i, name)   # active wins, then earliest row
        if icao not in best or cand[:2] > best[icao][:2]:
            best[icao] = cand
    table = {code: v[2] for code, v in best.items()}
    table.update(_OVERRIDES)
    return dict(sorted(table.items()))


def write(table, out=OUT):
    with open(out, "w", encoding="utf-8") as fh:
        fh.write('"""Generated by prestoradar/make_airlines.py -- do not edit by hand.\n\n')
        fh.write("Source : OpenFlights airlines.dat (ODbL), plus make_airlines.py's _OVERRIDES\n")
        fh.write("Key    : ICAO airline code -- the 3-letter prefix an ADS-B callsign starts with\n")
        fh.write("Count  : %d operators\n" % len(table))
        fh.write('"""\n\n')
        fh.write("OPERATORS = {\n")
        for code, name in table.items():
            fh.write("    %r: %r,\n" % (code, name))
        fh.write("}\n")


def main():
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--source", metavar="PATH",
                    help="local airlines.dat instead of fetching from OpenFlights")
    ap.add_argument("--all", action="store_true",
                    help="every ICAO code, not just active carriers (~5.8k)")
    ap.add_argument("--keep", metavar="FILE",
                    help="also keep ICAO codes listed one-per-line in FILE")
    args = ap.parse_args()

    keep = ()
    if args.keep:
        with open(args.keep, encoding="utf-8") as fh:
            keep = fh.read().split()
    table = build(args.source, keep_all=args.all, keep=keep)
    write(table)
    size = os.path.getsize(OUT)
    print("wrote %s: %d operators, %.1f KB" % (OUT, len(table), size / 1024))
    return 0


if __name__ == "__main__":
    sys.exit(main())
